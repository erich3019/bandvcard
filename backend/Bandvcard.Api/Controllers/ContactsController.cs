using Bandvcard.Api.Data;
using Bandvcard.Api.Entities;
using Bandvcard.Api.Storage;
using Microsoft.AspNetCore.Mvc;
using Microsoft.AspNetCore.OData.Deltas;
using Microsoft.AspNetCore.OData.Query;
using Microsoft.AspNetCore.OData.Results;
using Microsoft.AspNetCore.OData.Routing.Controllers;
using Microsoft.EntityFrameworkCore;

namespace Bandvcard.Api.Controllers;

public class ContactsController(
    BandvcardDbContext db,
    IPhotoStorage photos,
    ICurrentUser currentUser,
    ILogger<ContactsController> logger) : ODataController
{
    // Users work only with the contacts they captured themselves; admins with all of them.
    // Everything in this controller goes through this, so a foreign contact looks like a missing one.
    private IQueryable<Contact> Visible =>
        currentUser.IsAdmin ? db.Contacts : db.Contacts.Where(c => c.CreatedBy == currentUser.Name);

    [EnableQuery(PageSize = 100)]
    public IQueryable<Contact> Get() => Visible;

    [EnableQuery]
    public SingleResult<Contact> Get(Guid key) =>
        SingleResult.Create(Visible.Where(c => c.Id == key));

    public async Task<IActionResult> Post([FromBody] Contact contact)
    {
        if (!ModelState.IsValid)
        {
            return BadRequest(ModelState);
        }

        // The ID is always generated by the backend.
        contact.Id = Guid.Empty;
        if (await PhotoBelongsToSomeoneElseAsync(contact))
        {
            return BadRequest("The photo link belongs to another user's contact.");
        }

        if (!await EnsurePostalCodeAsync(contact))
        {
            return BadRequest(
                $"Postal code '{contact.PostalCode}' is not in the postal code directory and no city was given to add it.");
        }

        db.Contacts.Add(contact);
        await db.SaveChangesAsync();
        return Created(contact);
    }

    public async Task<IActionResult> Patch(Guid key, [FromBody] Delta<Contact> delta)
    {
        if (!ModelState.IsValid)
        {
            return BadRequest(ModelState);
        }

        var contact = await Visible.FirstOrDefaultAsync(c => c.Id == key);
        if (contact is null)
        {
            return NotFound();
        }

        delta.Patch(contact);
        if (contact.Id != key)
        {
            return BadRequest("The ID of a contact cannot be changed.");
        }

        if (await PhotoBelongsToSomeoneElseAsync(contact))
        {
            return BadRequest("The photo link belongs to another user's contact.");
        }

        if (!await EnsurePostalCodeAsync(contact))
        {
            return BadRequest(
                $"Postal code '{contact.PostalCode}' is not in the postal code directory and no city was given to add it.");
        }

        await db.SaveChangesAsync();
        return Updated(contact);
    }

    public async Task<IActionResult> Delete(Guid key)
    {
        var contact = await Visible.FirstOrDefaultAsync(c => c.Id == key);
        if (contact is null)
        {
            return NotFound();
        }

        db.Contacts.Remove(contact);
        await db.SaveChangesAsync();
        await DeleteUnusedPhotoAsync(contact.PhotoLink);
        return NoContent();
    }

    // Without this, pointing a contact at someone else's photo would unlock that photo.
    private async Task<bool> PhotoBelongsToSomeoneElseAsync(Contact contact) =>
        !currentUser.IsAdmin
        && PhotoLinks.TryGetKey(contact.PhotoLink, out _)
        && await db.Contacts.AnyAsync(c => c.PhotoLink == contact.PhotoLink && c.CreatedBy != currentUser.Name);

    // Runs after the contact is gone. A photo that cannot be removed only leaves an unused
    // file behind, so it is logged and does not fail the request.
    private async Task DeleteUnusedPhotoAsync(string? photoLink)
    {
        if (!PhotoLinks.TryGetKey(photoLink, out var key)
            || await db.Contacts.AnyAsync(c => c.PhotoLink == photoLink))
        {
            return;
        }

        try
        {
            await photos.DeleteAsync(key, HttpContext.RequestAborted);
        }
        catch (Exception e)
        {
            logger.LogWarning(e, "Could not delete photo {Key} of a deleted contact", key);
        }
    }

    // The directory grows with the captured cards: an unknown postal code is added with the
    // contact's city as its place name. Without a city there is nothing to add.
    private async Task<bool> EnsurePostalCodeAsync(Contact contact)
    {
        if (contact.PostalCode is null || await db.PostalCodes.AnyAsync(e => e.PostalCode == contact.PostalCode))
        {
            return true;
        }

        if (string.IsNullOrWhiteSpace(contact.City))
        {
            return false;
        }

        db.PostalCodes.Add(new PostalCodeEntry { PostalCode = contact.PostalCode, PlaceName = contact.City.Trim() });
        return true;
    }
}
