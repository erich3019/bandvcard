using Bandvcard.Api.Data;
using Bandvcard.Api.Entities;
using Microsoft.AspNetCore.Mvc;
using Microsoft.AspNetCore.OData.Deltas;
using Microsoft.AspNetCore.OData.Query;
using Microsoft.AspNetCore.OData.Results;
using Microsoft.AspNetCore.OData.Routing.Controllers;
using Microsoft.EntityFrameworkCore;

namespace Bandvcard.Api.Controllers;

public class ContactsController(BandvcardDbContext db) : ODataController
{
    [EnableQuery(PageSize = 100)]
    public IQueryable<Contact> Get() => db.Contacts;

    [EnableQuery]
    public SingleResult<Contact> Get(Guid key) =>
        SingleResult.Create(db.Contacts.Where(c => c.Id == key));

    public async Task<IActionResult> Post([FromBody] Contact contact)
    {
        if (!ModelState.IsValid)
        {
            return BadRequest(ModelState);
        }

        // The ID is always generated by the backend.
        contact.Id = Guid.Empty;
        if (!await EnsurePostalCodeAsync(contact))
        {
            return BadRequest(
                $"Postal code '{contact.PostalCode}' is not in the postal code directory and no city was given to add it.");
        }

        db.Contacts.Add(contact);
        await db.SaveChangesAsync();
        return Created(contact);
    }

    public async Task<IActionResult> Patch(Guid key, [FromBody] Delta<Contact> delta)
    {
        if (!ModelState.IsValid)
        {
            return BadRequest(ModelState);
        }

        var contact = await db.Contacts.FindAsync(key);
        if (contact is null)
        {
            return NotFound();
        }

        delta.Patch(contact);
        if (contact.Id != key)
        {
            return BadRequest("The ID of a contact cannot be changed.");
        }

        if (!await EnsurePostalCodeAsync(contact))
        {
            return BadRequest(
                $"Postal code '{contact.PostalCode}' is not in the postal code directory and no city was given to add it.");
        }

        await db.SaveChangesAsync();
        return Updated(contact);
    }

    public async Task<IActionResult> Delete(Guid key)
    {
        var contact = await db.Contacts.FindAsync(key);
        if (contact is null)
        {
            return NotFound();
        }

        db.Contacts.Remove(contact);
        await db.SaveChangesAsync();
        return NoContent();
    }

    // The directory grows with the captured cards: an unknown postal code is added with the
    // contact's city as its place name. Without a city there is nothing to add.
    private async Task<bool> EnsurePostalCodeAsync(Contact contact)
    {
        if (contact.PostalCode is null || await db.PostalCodes.AnyAsync(e => e.PostalCode == contact.PostalCode))
        {
            return true;
        }

        if (string.IsNullOrWhiteSpace(contact.City))
        {
            return false;
        }

        db.PostalCodes.Add(new PostalCodeEntry { PostalCode = contact.PostalCode, PlaceName = contact.City.Trim() });
        return true;
    }
}
