using Bandvcard.Api.Data;
using Bandvcard.Api.Entities;
using Microsoft.AspNetCore.Mvc;
using Microsoft.AspNetCore.OData.Deltas;
using Microsoft.AspNetCore.OData.Query;
using Microsoft.AspNetCore.OData.Results;
using Microsoft.AspNetCore.OData.Routing.Controllers;
using Microsoft.EntityFrameworkCore;

namespace Bandvcard.Api.Controllers;

public class OpportunitiesController(BandvcardDbContext db, ContactVisibility visibility) : ODataController
{
    // An opportunity is as visible as its contact.
    private IQueryable<Opportunity> Visible =>
        db.Opportunities.Where(o => visibility.Contacts.Any(c => c.Id == o.ContactId));

    private Task<bool> ContactIsVisibleAsync(Guid contactId) =>
        visibility.Contacts.AnyAsync(c => c.Id == contactId);

    [EnableQuery(PageSize = 100)]
    public IQueryable<Opportunity> Get() => Visible;

    [EnableQuery]
    public SingleResult<Opportunity> Get(Guid key) =>
        SingleResult.Create(Visible.Where(o => o.Id == key));

    public async Task<IActionResult> Post([FromBody] Opportunity opportunity)
    {
        if (!ModelState.IsValid)
        {
            return BadRequest(ModelState);
        }

        if (!await ContactIsVisibleAsync(opportunity.ContactId))
        {
            return BadRequest("The contact of the opportunity does not exist.");
        }

        if (NormalizeText(opportunity) is { } problem)
        {
            return BadRequest(problem);
        }

        // The ID is always generated by the backend.
        opportunity.Id = Guid.Empty;
        opportunity.Contact = null;
        db.Opportunities.Add(opportunity);
        await db.SaveChangesAsync();
        return Created(opportunity);
    }

    public async Task<IActionResult> Patch(Guid key, [FromBody] Delta<Opportunity> delta)
    {
        if (!ModelState.IsValid)
        {
            return BadRequest(ModelState);
        }

        var opportunity = await Visible.FirstOrDefaultAsync(o => o.Id == key);
        if (opportunity is null)
        {
            return NotFound();
        }

        var contactId = opportunity.ContactId;
        delta.Patch(opportunity);
        if (opportunity.Id != key || opportunity.ContactId != contactId)
        {
            return BadRequest("The ID and the contact of an opportunity cannot be changed.");
        }

        if (NormalizeText(opportunity) is { } problem)
        {
            return BadRequest(problem);
        }

        await db.SaveChangesAsync();
        return Updated(opportunity);
    }

    public async Task<IActionResult> Delete(Guid key)
    {
        var opportunity = await Visible.FirstOrDefaultAsync(o => o.Id == key);
        if (opportunity is null)
        {
            return NotFound();
        }

        db.Opportunities.Remove(opportunity);
        await db.SaveChangesAsync();
        return NoContent();
    }

    // Trims the text and returns what is wrong with it, or null if it is fine.
    private static string? NormalizeText(Opportunity opportunity)
    {
        opportunity.Text = opportunity.Text?.Trim() ?? "";
        return opportunity.Text.Length switch
        {
            0 => "The text of an opportunity must not be empty.",
            > Opportunity.MaxTextLength =>
                $"The text of an opportunity must not be longer than {Opportunity.MaxTextLength} characters.",
            _ => null,
        };
    }
}
